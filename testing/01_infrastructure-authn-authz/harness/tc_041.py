# Refresh response = {access_token, refresh_token, token_type}; NO `user` field.

async def main() -> None:
    sfx = stamp()
    slug = f"token-{sfx}"
    admin_email = f"admin-{sfx}@token.example.com"
    print(f"[setup] namespace=token-{sfx} slug={slug} admin={admin_email}")

    async with _client() as c:
        plat = await platform_login(c)
        ob = await onboard_org(c, plat, name=f"Token Org {sfx}", slug=slug, admin_email=admin_email)
        print(f"[setup] onboard_org -> {ob.status_code}")
        assert ob.status_code == 201, ob.text

        lr = await login(c, admin_email, DEFAULT_PW)
        assert lr.status_code == 200, lr.text
        login_keys = sorted(lr.json().keys())
        print(f"[step1] login -> {lr.status_code}  body_keys={login_keys}  has_user={'user' in lr.json()}")
        r0 = lr.json()["refresh_token"]

        rr = await c.post("/auth/refresh", json={"refresh_token": r0})
        body = rr.json()
        keys = sorted(body.keys())
        print(f"[step2] refresh -> {rr.status_code}")
        print(f"[step2] refresh body keys = {keys}")
        print(f"[step2] full refresh body = {body if 'user' not in body else 'CONTAINS user!'}")
        print(f"[step2] token_type = {body.get('token_type')!r}")
        print(f"[step2] 'user' in body = {'user' in body}")

        held = (
            rr.status_code == 200
            and set(keys) == {"access_token", "refresh_token", "token_type"}
            and body.get("token_type") == "bearer"
            and "user" in lr.json()  # control: login DID include user
        )
        print(f"[verdict] excludes-user HELD={held} (refresh keys exact 3, no user; login had user)")


asyncio.run(main())
