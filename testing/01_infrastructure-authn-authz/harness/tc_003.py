# TC-IA-003 — Chunked / no-Content-Length large body bypasses the cap
#             (Adversarial, CONFIRMS-DOCUMENTED). Sev Low.
# Hypothesis: MaxBodySizeMiddleware only inspects the DECLARED Content-Length
# header (middleware.py:30-32). Sending a >1 MiB body via an async generator forces
# httpx to use Transfer-Encoding: chunked with NO Content-Length, so the guard's
# `content_length is not None` check is skipped — the body is buffered and the route
# runs. Documented in the middleware docstring. PROOF = status is NOT 413 for an
# oversized chunked body (we expect 422 on invalid JSON, which proves the >1 MiB
# body sailed past the cap into the route). The middleware docstring documents this.
# Contrast control: TC-IA-002 sends the SAME size WITH Content-Length → 413.
# ─────────────────────────────────────────────────────────────────────────────

async def main() -> None:
    big_size = 2 * 1024 * 1024  # ~2 MiB, double the 1 MiB cap
    chunk = b"A" * (256 * 1024)  # 256 KiB chunks
    n_chunks = big_size // len(chunk)

    async def body_stream():
        # Yielding from an async generator forces httpx into chunked transfer
        # encoding with NO Content-Length header — the bypass vector.
        for _ in range(n_chunks):
            yield chunk

    async with _client() as c:
        # Inspect the headers httpx will send: confirm NO content-length, chunked TE.
        req = c.build_request("POST", "/auth/login", content=body_stream(),
                              headers={"content-type": "application/json"})
        print("=== POST /auth/login (chunked, NO declared Content-Length) ===")
        print("declared content-length header present:", "content-length" in req.headers)
        print("transfer-encoding header:", req.headers.get("transfer-encoding"))
        print("intended body size:", big_size, "bytes (cap=1048576)")

        r = await c.send(req)
        print("status:", r.status_code)
        print("body:", r.text[:500])
        print("--- assertions ---")
        print("status != 413 (cap bypassed):", r.status_code != 413)
        print("body was processed by route (422 invalid-JSON expected):", r.status_code == 422)


asyncio.run(main())
